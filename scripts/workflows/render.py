"""Generate docs/workflows/<ID>.md, docs/workflows/README.md and spec/acceptance.yaml from data.py.
Every main path, must-hold and failure case of a BUILD or MANUAL workflow becomes an acceptance ID.
--check: exit 1 if the committed files differ from what would be generated (CI drift check).
A page's 'Status:' line belongs to the tasks that implement it (CLAUDE.md, done means), so the committed one is kept."""
import re
import sys
from collections import Counter
from pathlib import Path

import yaml
from data import W

ROOT = Path(__file__).resolve().parents[2]
DOMAINS = {
    "A": ("Access", "Workspace Settings (People, Your account); Onboarding Flow; Account Recovery"),
    "B": ("Workspace and allowance", "Onboarding Flow; Workspace Settings; Plans and Checkout (third and fourth label)"),
    "C": ("Products", "Nutrivo 2.0 (board, product)"),
    "D": ("Label checks", "Nutrivo 2.0 (label report, artwork pins, coverage node); Mobile; Empty and Error States"),
    "E": ("Briefs", "Nutrivo 2.0 (new product brief)"),
    "F": ("Portfolio", "Nutrivo 2.0 (board); Missing Surfaces (portfolio at scale, bulk re-check)"),
    "G": ("Registrations", "Nutrivo 2.0 (registration packs)"),
    "H": ("Documents and suppliers", "Nutrivo 2.0 (documents); Email Templates"),
    "I": ("Reports and verification", "Export - Label Report; Certificate of Check; Action Plan; Nutrivo 2.0"),
    "J": ("Regulatory change", "Missing Surfaces (alerts inbox, horizon)"),
    "K": ("Content operations", "Nutrivo 2.0 (term register, coverage node); internal /admin"),
    "L": ("Compliance Worker", "Nutrivo 2.0 (Worker panel); Missing Surfaces (help)"),
    "M": ("Billing", "Plans and Checkout; Billing Settings; Priced Ladder"),
    "N": ("Partners", "Partner Tier; Partner Upsell"),
    "O": ("Operations", "Email Templates; Workspace Settings (audit log, data and retention)"),
    "P": ("Public", "Coverage - public; Pricing Page; Landing Page; Marketing Site"),
}
NOTE = ("<sub>Steps, must-hold and failure cases were reconstructed on 8 Oct 2026 from the Handoff, the Backend Action "
        "Register and the Workflow Register PDF, because the original HTML's text was unavailable. The database line is "
        "the register's own text, in its own naming (docs/03-data-model.md maps it). Changes go through "
        "scripts/workflows/data.py and a founder-approved PR.</sub>")


def tests_for(x):
    if x["scope"] == "LATER":
        return {}
    t = {f"{x['id']}.main": f"{x['name']}: the main path works end to end"}
    t.update({f"{x['id']}.must.{n}": m for n, m in enumerate(x["must"], 1)})
    t.update({f"{x['id']}.fail.{n}": f for n, f in enumerate(x["fail"], 1)})
    return t


def bullets(items, empty="—"):
    return "\n".join(f"- {i}" for i in items) if items else empty


def page(x):
    domain, design = DOMAINS[x["id"][0]]
    steps = "\n".join(f"{n}. {s}" for n, s in enumerate(x["steps"], 1))
    ids = tests_for(x)
    acc = "\n".join(f"- `{i}` {t}" for i, t in ids.items()) or "After launch: no acceptance IDs yet."
    return f"""# {x['id']} · {x['name']}

| Domain | Register status | Scope | Milestone |
|---|---|---|---|
| {domain} | {x['st']} | {x['scope']} | {x['ms']} |

**Actor · trigger:** {x['who']}  
**Design:** {design}

## Steps
{steps}

## Database (Workflow Register)
{x['db']}

**Depends on:** {x['dep']}

## Must hold
{bullets(x['must'])}

## Failure and edge cases
{bullets(x['fail'])}

## Acceptance IDs (each needs a test carrying the ID in its title; docs/19)
{acc}

**Related backend rows:** {', '.join(x['refs']) or '—'}

Status: not started

{NOTE}
"""


def outputs():
    st, sc = Counter(x["st"] for x in W), Counter(x["scope"] for x in W)
    assert len(W) == 71 and len({x["id"] for x in W}) == 71
    assert st == {"DRAWN": 48, "PART": 13, "NOT DRAWN": 3, "BACKEND": 7}, st
    out = {f"docs/workflows/{x['id']}.md": page(x) for x in W}
    rows = "\n".join(f"| [{x['id']}]({x['id']}.md) | {x['name']} | {DOMAINS[x['id'][0]][0]} | {x['st']} | {x['scope']} | "
                     f"{x['ms']} | {len(tests_for(x))} |" for x in W)
    total = sum(len(tests_for(x)) for x in W if x["scope"] == "BUILD")
    out["docs/workflows/README.md"] = f"""# Workflows

All 71 workflows of the Workflow Register (25 Sep 2026): {st['DRAWN']} drawn, {st['PART']} partly drawn,
{st['NOT DRAWN']} not drawn, {st['BACKEND']} backend-only. Scope: **{sc['BUILD']} BUILD** (the MVP),
**{sc['MANUAL']} MANUAL** (people with scripts), **{sc['LATER']} LATER** (after launch).
**{total} required acceptance IDs** across the BUILD workflows (spec/acceptance.yaml).
Generated by `make workflows` from `scripts/workflows/data.py`; edit the data, not these files.

| ID | Workflow | Domain | Register | Scope | Milestone | Acceptance IDs |
|---|---|---|---|---|---|---|
{rows}
"""
    spec = {"workflows": {x["id"]: {"name": x["name"], "scope": x["scope"], "milestone": x["ms"], "tests": tests_for(x)}
                          for x in W}}
    out["spec/acceptance.yaml"] = ("# Generated by scripts/workflows/render.py from scripts/workflows/data.py. Do not edit.\n"
                                   "# Every ID needs a test carrying it in its title (docs/19-testing-cadence.md).\n"
                                   + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=200))
    return out, total


def keep_status(out):
    for p, c in out.items():
        f = ROOT / p
        if p.startswith("docs/workflows/") and p != "docs/workflows/README.md" and f.exists():
            committed = re.findall(r"^Status: .*$", f.read_text(encoding="utf-8"), re.M)
            if committed:
                out[p] = c.replace("\nStatus: not started\n", f"\n{committed[-1]}\n", 1)


def main():
    out, total = outputs()
    keep_status(out)
    if "--check" in sys.argv:
        stale = [p for p, c in out.items() if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != c]
        if stale:
            print("generated files are stale; run `make workflows`:\n  " + "\n  ".join(stale))
            sys.exit(1)
        print(f"generated workflow docs and spec/acceptance.yaml are current ({total} required IDs)")
        return
    for p, c in out.items():
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(c, encoding="utf-8")
    print(f"rendered 71 workflows and spec/acceptance.yaml ({total} required acceptance IDs)")


if __name__ == "__main__":
    main()
